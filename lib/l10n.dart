final l10nProvider = Provider<L10n>((ref) {
  final settings = ref.watch(settingsProvider);
  final systemLanguage =
      WidgetsBinding.instance.platformDispatcher.locale.languageCode;
  String languageCode;
  switch (settings.selectedLanguage) {
    case 'Français':
      languageCode = 'fr';
      break;
    case 'English':
      languageCode = 'en';
      break;
    case 'Español':
      languageCode = 'es';
      break;
    case 'Português':
      languageCode = 'pt';
      break;
    case 'Русский':
      languageCode = 'ru';
      break;
    case '中文':
      languageCode = 'zh';
      break;
    case 'Deutsch':
      languageCode = 'de';
      break;
    case 'Italiano':
      languageCode = 'it';
      break;
    default:
      languageCode = L10n._localizedValues.containsKey(systemLanguage)
          ? systemLanguage
          : 'en';
  }
  return L10n(languageCode);
});

extension L10nExtension on BuildContext {
  L10n l10n(WidgetRef ref) => ref.watch(l10nProvider);
}
