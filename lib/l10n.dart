  String getKeyOf(String word){
    if (_localizedValues.isNotEmpty){
      for(String languageKey in _localizedValues.keys){
        if (_localizedValues[languageKey]!.isNotEmpty){
          for (String wordKey in _localizedValues[languageKey]!.keys){
            if (word == _localizedValues[languageKey]![wordKey]){
              return wordKey;
            }
          }
        }
      }
    }

    return word;
  }

